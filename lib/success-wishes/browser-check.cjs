const { chromium } = require(require.resolve('playwright', { paths: [process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES] }))
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({headless:true})
  const results=[]
  for (const width of [360,390,768,1440]) {
    const context = await browser.newContext({viewport:{width,height:900}})
    const page = await context.newPage()
    const errors=[];page.on('pageerror',e=>errors.push(e.message))
    await page.goto('http://localhost:3000/success-wishes',{waitUntil:'networkidle',timeout:90000})
    await page.getByRole('heading',{name:/A little encouragement/}).waitFor()
    const mutations=[]
    page.on('request',r=>{if(r.url().includes('/api/success-wishes/')&&r.method()!=='GET')mutations.push(r.url())})
    await page.getByRole('button',{name:/New Beginnings/}).click()
    await page.getByRole('textbox',{name:/Candidate.s name/}).fill('Synthetic Candidate')
    await page.getByRole('textbox',{name:/Your name/}).fill('Synthetic Sender')
    const wish='Synthetic UI test: wishing you confidence.'
    await page.getByRole('textbox',{name:/Your personal wish/}).fill(wish)
    const download=page.waitForEvent('download')
    await page.getByRole('button',{name:/Download card/}).click()
    assert.equal((await download).suggestedFilename(),'vibeschool-success-wishes.png')
    await page.getByRole('button',{name:/Choose school.*candidate/}).click()
    await page.getByRole('heading',{name:'Let them know you believe.'}).waitFor()
    assert.equal(await page.getByRole('textbox',{name:/Candidate.s name/}).inputValue(),'Synthetic Candidate')
    assert.equal(await page.getByRole('textbox',{name:/Your encouragement/}).inputValue(),wish)
    await page.getByRole('button',{name:/Preview wish/}).click()
    await page.getByRole('heading',{name:'Open your special wish'}).waitFor()
    assert((await page.locator('text=Synthetic UI test: wishing you confidence.').count())>0,'exact wish text must appear in the card preview')
    assert((await page.locator('text=Selected design: botanical').count())>0,'selected card design must carry into the send review')
    assert.equal(await page.getByRole('button',{name:/Submit wish/}).isDisabled(),true,'disabled service cannot submit a message')
    await page.getByRole('button',{name:/Edit/}).click()
    await page.getByRole('button',{name:'Candidate inbox'}).click()
    await page.getByRole('heading',{name:'Open your messages'}).waitFor()
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'horizontal overflow')
    const config=await page.request.get('http://localhost:3000/api/success-wishes/config')
    assert.equal((await config.json()).enabled,false)
    assert.match(config.headers()['cache-control'],/no-store/)
    await page.screenshot({path:`/tmp/success-wishes-${width}.png`,fullPage:true})
    assert.deepEqual(mutations,[],'synthetic local review must not call message mutation APIs')
    assert.deepEqual(errors,[])
    results.push({width,overflow:false,pageErrors:errors,preview:true,candidateInbox:true,disabled:true,noMutationCalls:true})
    await context.close()
  }
  process.stdout.write(JSON.stringify({test:'real disabled service UI; no mocked API',results},null,2)+'\n')
  await browser.close()
})().catch(e=>{process.stderr.write(String(e)+"\n");process.exit(1)})
