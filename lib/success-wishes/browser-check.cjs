const { chromium } = require(require.resolve('playwright', { paths: [process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES] }))
const assert = require('node:assert/strict')
const fs = require('node:fs')
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || chromium.executablePath()
;(async () => {
  assert(fs.existsSync(executablePath), `Chromium executable not found: ${executablePath}`)
  const browser = await chromium.launch({ headless: true, executablePath })
  const results = []
  for (const width of [390, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: 900 } })
    const page = await context.newPage()
    const errors = []
    const mutations = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => {
      if (request.url().includes('/api/success-wishes/') && request.method() !== 'GET') mutations.push(request.url())
    })
    await page.goto('http://localhost:3000/success-wishes', { waitUntil: 'networkidle', timeout: 90000 })
    await page.getByRole('heading', { name: /A little encouragement/ }).waitFor()
    assert.equal(await page.getByRole('button', { name: /Golden Hour/ }).count(), 1)
    assert.equal(await page.getByRole('button', { name: /New Beginnings/ }).count(), 1)
    assert.equal(await page.getByRole('button', { name: /Bright Star/ }).count(), 1)
    assert.equal(await page.getByRole('button', { name: /Above & Beyond/ }).count(), 1)
    assert.equal(await page.getByRole('button', { name: /Open candidate inbox/ }).count(), 0, 'the school-code inbox is not presented as the candidate journey')

    const downloadButton = page.getByRole('button', { name: /Download card/ })
    assert.equal(await downloadButton.isDisabled(), true, 'download stays disabled until the exam year is entered')
    await page.getByRole('textbox', { name: /Candidate.s name/ }).fill('John Mwangi')
    await page.getByRole('textbox', { name: /Exam year/ }).fill('2026')
    if (width === 1440) await page.getByRole('textbox', { name: /School \(optional\)/ }).fill('Gilgil Township')
    await page.getByRole('textbox', { name: /Your name/ }).fill('Synthetic sender')
    const wish = 'You have worked hard. We believe in you. Go forward with courage.'
    await page.getByRole('textbox', { name: /Your personal wish/ }).fill(wish)
    await page.getByRole('button', { name: /New Beginnings/ }).click()
    const preview = page.locator('.live svg').last()
    const accessibleCard = await preview.getAttribute('aria-label')
    assert.match(accessibleCard, /New Beginnings Success Wishes card for John Mwangi/)
    assert.match(accessibleCard, /exam year 2026/)
    assert.match(accessibleCard, /Message: You have worked hard\. We believe in you\. Go forward with courage\./)
    if (width === 1440) assert.match(accessibleCard, /Gilgil Township/)
    else assert.doesNotMatch(accessibleCard, /Gilgil Township/, 'school remains optional')
    assert.match(await page.locator('main').innerText(), /has not saved it to a candidate inbox or delivered it/i)

    const download = page.waitForEvent('download')
    await downloadButton.click()
    assert.equal((await download).suggestedFilename(), 'vibeschool-success-wishes.png')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `no horizontal overflow at ${width}px`)
    const config = await page.request.get('http://localhost:3000/api/success-wishes/config')
    assert.equal((await config.json()).enabled, false, 'private sending remains disabled')
    assert.match(config.headers()['cache-control'], /no-store/)
    assert.deepEqual(mutations, [], 'local card creation must not call server mutation APIs')
    assert.deepEqual(errors, [])
    await page.screenshot({ path: `/tmp/success-wishes-${width}.png`, fullPage: true })
    results.push({ width, fourDesigns: true, cardPreview: true, schoolOptional: true, downloadable: true, deliveryDisabled: true, pageErrors: errors })
    await context.close()
  }
  process.stdout.write(JSON.stringify({ test: 'Success Wishes card creator in real Chromium; private service disabled; no mocked API', results }, null, 2) + '\n')
  await browser.close()
})().catch(error => { process.stderr.write(String(error) + '\n'); process.exit(1) })
