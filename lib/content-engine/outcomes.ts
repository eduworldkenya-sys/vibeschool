/**
 * Replaces the full set of author-selected outcome links for a chapter.
 * Existing selected links are upserted first (preserving their id/created_at),
 * then any link no longer present in outcomeIds is removed. This does not
 * touch the auto-synced 'creator_claimed' links generated by the
 * ce_sync_chapter_learning_outcomes trigger from the legacy
 * vibe_chapters.learning_outcomes text array — those are a separate
 * authority and are reconciled independently on chapter save.
 */
export async function replaceChapterOutcomeLinks(
  client: ContentEngineClient,
  input: ReplaceChapterOutcomeLinksInput,
): Promise<ChapterLearningOutcomeLink[]> {
  const operation = 'replaceChapterOutcomeLinks'
  const publicationId = assertRequiredId(
    input.publicationId,
    'publicationId',
    operation,
  )
  const chapterId = assertRequiredId(
    input.chapterId,
    'chapterId',
    operation,
  )
  const outcomeIds = dedupeOutcomeIds(input.outcomeIds, operation)
  const alignmentStrength =
    input.alignmentStrength ?? DEFAULT_ALIGNMENT_STRENGTH

  const authorId = await requireAuthenticatedUserId(client, operation)

  if (outcomeIds.length === 0) {
    const { error: deleteAllError } = await client
      .from('chapter_learning_outcome_links')
      .delete()
      .eq('chapter_id', chapterId)

    if (deleteAllError) {
      throw toContentEngineError(operation, deleteAllError)
    }

    return []
  }

  const rows = outcomeIds.map((outcomeId, index) => ({
    publication_id: publicationId,
    chapter_id: chapterId,
    outcome_id: outcomeId,
    alignment_strength: alignmentStrength,
    sequence: index + 1,
    created_by: authorId,
  }))

  const { data, error } = await client
    .from('chapter_learning_outcome_links')
    .upsert(rows, { onConflict: 'chapter_id,outcome_id' })
    .select('*')

  if (error) {
    throw toContentEngineError(operation, error)
  }

  const keepList = outcomeIds.map(id => `"${id}"`).join(',')

  const { error: staleError } = await client
    .from('chapter_learning_outcome_links')
    .delete()
    .eq('chapter_id', chapterId)
    .not('outcome_id', 'in', `(${keepList})`)

  if (staleError) {
    throw toContentEngineError(operation, staleError)
  }

  return data
}

