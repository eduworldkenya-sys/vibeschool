/**
 * The author editor works with legacy client-generated block ids until a
 * block is persisted and reconciled into public.content_blocks (see
 * CE-003). Block-level outcome linking is only possible after that
 * reconciliation, so callers must resolve the authoritative id first.
 * Returns null if the block has not been reconciled yet — callers should
 * treat that as "save the chapter first", not as an error.
 */
export async function resolveContentBlockId(
  client: ContentEngineClient,
  chapterId: string,
  legacyBlockId: string,
): Promise<string | null> {
  const operation = 'resolveContentBlockId'
  const cId = assertRequiredId(chapterId, 'chapterId', operation)
  const legacyId = assertRequiredId(
    legacyBlockId,
    'legacyBlockId',
    operation,
  )

  const { data, error } = await client
    .from('content_blocks')
    .select('id')
    .eq('chapter_id', cId)
    .eq('legacy_block_id', legacyId)
    .maybeSingle()

  if (error) {
    throw toContentEngineError(operation, error)
  }

  return data?.id ?? null
}
