import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import { GRADE4_ENGLISH_UNITS as units, GRADE4_ENGLISH_THEMES, GRADE4_ENGLISH_PREFIX, GRADE4_ENGLISH_SOURCE_URL, GRADE4_ENGLISH_LESSONS, GRADE4_ENGLISH_OUTCOMES, GRADE4_ENGLISH_WEEKLY_ALLOCATION } from '../lib/teaching/grade4EnglishCatalog.mjs'
import { buildGrade1AnnualSchemeDraft } from '../lib/teaching/creativeSchemeDraft.mjs'

const read=p=>readFileSync(new URL(p,import.meta.url),'utf8')
const map=read('../components/teacher/curriculum/Grade4EnglishMap.tsx')
const page=read('../app/teacher/scheme/AuthoritySchemePage.jsx')
const hub=read('../app/teacher/subjecthub/page.tsx')
const index=read('../lib/curriculum/grade4EnglishReference.ts')
const sql=read('../supabase/migrations/20261111153500_grade4_english_kicd_scheme.sql')

assert.equal(GRADE4_ENGLISH_THEMES.length,13)
assert.deepEqual(GRADE4_ENGLISH_THEMES.map(x=>x.number),Array.from({length:13},(_,i)=>i+1))
assert.equal(units.length,52)
assert.equal(new Set(units.map(u=>u.id)).size,52)
assert.equal(new Set(units.map(u=>u.strand)).size,4)
assert.equal(GRADE4_ENGLISH_LESSONS,150)
assert.equal(GRADE4_ENGLISH_OUTCOMES,156)
assert.equal(GRADE4_ENGLISH_WEEKLY_ALLOCATION,5)
assert.equal(GRADE4_ENGLISH_PREFIX,'VS-CUR-G04-EN-2026')
assert.ok(GRADE4_ENGLISH_SOURCE_URL.startsWith('https://kicd.ac.ke/'))
assert.ok(units.every(u=>u.outcomes.length===3&&u.experiences.length>=2&&u.inquiry.length>=1&&u.resources&&u.assessment))
for(const t of GRADE4_ENGLISH_THEMES){
 const skills=units.filter(u=>u.theme===t.number)
 assert.equal(skills.length,4,'Every theme has four language skills')
 assert.deepEqual(skills.map(u=>u.strand),['Listening and Speaking','Reading','Grammar in Use','Writing'])
 assert.ok(skills.every(u=>u.title.includes(t.name)),t.name+' missing theme identity')
}
const snapshot=sql.match(/jsonb_array_elements\(\$vs_g4_en\$([\s\S]*?)\$vs_g4_en\$::jsonb\) unit;/)
assert.ok(snapshot,'Migration must contain an exact immutable catalog snapshot')
assert.deepEqual(JSON.parse(snapshot[1]),units,'Database and app learning units must match')
const terms=[1,2,3].map(n=>({id:'t'+n,term:n}))
const weeks=terms.flatMap(t=>Array.from({length:10},(_,i)=>({term_id:t.id,week_number:i+1,week_type:'normal',school_id:null})))
const options={units,terms,termWeeks:weeks,weeklyAllocation:5,expectedUnitCount:52,gradeLabel:'Grade 4'}
const draft=buildGrade1AnnualSchemeDraft(options)
assert.equal(draft.error,null)
assert.equal(draft.items.length,150)
assert.equal(draft.weeks.length,30)
assert.equal(new Set(draft.items.map(x=>x.key)).size,150)
assert.deepEqual(new Set(draft.items.map(x=>x.unitId)),new Set(units.map(u=>u.id)))
assert.ok(draft.weeks.every(w=>draft.items.filter(x=>x.termId===w.termId&&x.week===w.week).length===5))
assert.deepEqual(buildGrade1AnnualSchemeDraft(options),draft,'Opening a teacher scheme must not write or change it')
assert.ok(buildGrade1AnnualSchemeDraft({...options,weeklyAllocation:4}).error,'Insufficient school allocation must fail closed')
assert.ok(buildGrade1AnnualSchemeDraft({...options,terms:terms.slice(0,2)}).error,'Incomplete term calendars fail closed')
for(const needle of ['GRADE4_ENGLISH_UNITS','mappedUnits[unit.id]','onPlanUnit(unit.id)','13 themes','Original KICD document','onToggleExisting','outcomes and learning experiences: awaiting source verification'])
 assert.ok(map.includes(needle),'Native English theme map missing '+needle)
for(const needle of ['isGrade4English','grade4_english_reader_bindings','GRADE4_ENGLISH_PREFIX','GRADE4_ENGLISH_UNITS','grade4EnglishCatalogError','mappedUnits={grade4EnglishCatalog}','isAutoScheme','commit_mapped_scheme_lesson','p_outcome_ids:item.outcomeIds'])
 assert.ok(page.includes(needle),'Canonical Scheme missing '+needle)
assert.ok(hub.includes('grade4EnglishClass')&&hub.includes('Open Grade 4 English curriculum'))
assert.ok(index.includes('GRADE4_ENGLISH_SUBSTRANDS')&&index.includes('GRADE4_ENGLISH_SOURCE'))
for(const token of ['authorization-test: public.grade4_english_reader_bindings','enable row level security',"source_type='creator_claimed'",'SCHEME_INVOKER_AUTHORITY_REQUIRED','GRADE4_ENGLISH_PERSISTENCE_INCOMPLETE',"on conflict(subject_id,grade,name,sub_strand) do nothing",'grade4_english_reader_bindings'])
 assert.ok(sql.includes(token),'Database safety requirement missing '+token)
assert.ok(!/truncate public\.cbc_strands|delete from public\.cbc_strands|insert into public\.scheme_of_work/i.test(sql),'Teacher history may not be overwritten or auto-saved')
console.log('Grade 4 English: 13 KICD themes · 52 canonical units · 156 VibeSchool outcomes · 150 proposed lessons · linked Scheme PASS')
