import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const source=read('lib/curriculum/grade6KiswahiliReference.ts')
const reader=read('components/teacher/curriculum/Grade6KiswahiliMap.tsx')
const scheme=read('app/teacher/scheme/AuthoritySchemePage.jsx')
const themes=JSON.parse(source.match(/export const GRADE6_KISWAHILI_THEMES = (\[[\s\S]*?\]) as const/)[1])
const units=JSON.parse(source.match(/export const GRADE6_KISWAHILI_UNITS = (\[[\s\S]*?\]) as const/)[1])
assert.equal(themes.length,11)
assert.equal(new Set(units.map(u=>u.code)).size,units.length)
assert.equal(units.length,53)
assert.deepEqual([...new Set(units.map(u=>u.strand))],[1,2,3,4])
assert.equal(units.reduce((n,u)=>n+u.lessons,0),115)
assert.ok(source.includes('GRADE6_KISWAHILI_PRINTED_TOTAL = 120'))
assert.ok(source.includes('GRADE6_KISWAHILI_WEEKLY_LESSONS = 4'))
assert.ok(source.includes('LATEST-6.8.2024-KISWAHILI-GRADE-6-Revised.pdf'))
assert.ok(source.includes('do not auto-allocate weeks'))
assert.ok(reader.includes('KICD') && reader.includes('GRADE6_KISWAHILI_ITEMISED_TOTAL'))
assert.ok(reader.includes('onOpenScheme') && reader.includes('kiswahili-grade6-search'))
assert.ok(scheme.includes('isGrade6Kiswahili') && scheme.includes('<Grade6KiswahiliMap'))
assert.ok(scheme.includes('isGrade6Kiswahili||isGrade9English'))
assert.ok(!scheme.includes('isAutoScheme = isGrade6Kiswahili'))
console.log('Grade 6 Kiswahili KICD-referenced structural reader: PASS (11 themes, 53 sub-strands, 4 periods weekly, unresolved 120-vs-115 allocation)')
