import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8')
const map = JSON.parse(read('../content/curriculum/grade-5/cre/kicd-2024-structural-reconciliation.json'))
const unitText = read('../content/curriculum/grade-5/cre/1.1-my-purpose-vibeschool-original-draft.md')
const units = map.strands.flatMap(s => s.units)

assert.equal(map.grade, 'Grade 5')
assert.equal(map.subject, 'Christian Religious Education')
assert.equal(map.strands.length, 5)
assert.equal(units.length, 30)
assert.equal(units.reduce((sum, unit) => sum + unit.suggested_lessons, 0), 90)
assert.equal(new Set(units.map(unit => unit.cbc_strand_id)).size, 30)
assert.equal(new Set(units.map(unit => unit.code)).size, 30)
assert.equal(map.counts.linked_outcomes, 17)
assert.equal(units.filter(unit => unit.linked_outcomes_at_baseline > 0).length, 4)
assert.equal(units.filter(unit => unit.linked_outcomes_at_baseline === 0).length, 26)
assert.ok(units.every(unit => unit.suggested_lessons === 3))
assert.equal(map.draft_textbook.chapters, 30)
assert.equal(map.draft_textbook.status, 'draft')
assert.match(map.authority.source_url, /^https:\/\/kicd\.ac\.ke\//)
assert.ok(!map.authority.source_exact_private_transcription_complete)
assert.ok(!map.authority.rights_scope_verified)
assert.match(unitText, /G5-CRE-1\.1-a/)
assert.match(unitText, /G5-CRE-1\.1-b/)
assert.match(unitText, /G5-CRE-1\.1-c/)
assert.match(unitText, /G5-CRE-1\.1-d/)
for (const i of [1,2,3]) assert.match(unitText,new RegExp('## Lesson '+i+' —'))
assert.match(unitText, /NOT PUBLISHED|Not published|not published/)
assert.doesNotMatch(unitText, /^# .*Answer Key/m)
console.log('Grade 5 CRE official structure, existing IDs, first-unit coverage and unpublished state: PASS')
