import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8')

test('Independent learner keeps one identity, reading resume and reachable practice', () => {
  const study = read('app/student/study/page.tsx')
  assert.match(study, /identity\?\.studentId/)
  assert.match(study, /getVibeLearnWorkstation\(/)
  assert.match(study, /continueLearning\.slice\(0,3\)/)
  assert.match(study, /safeInternalRoute\(item\.actionUrl\)/)
  assert.match(study, /\/student\/vibelearn\/topic-practice/)
  assert.doesNotMatch(study, /if\s*\([^)]*schoolId[^)]*\)\s*return\s*null/)
})

test('Practice keeps submitted answers independent of feedback read availability', () => {
  const practice = read('components/student/CanonicalTopicPractice.tsx')
  assert.match(practice, /startOrResumeAttempt\(/)
  assert.match(practice, /fetchFeedback\(attempt\.attemptId\)\.catch\(\(\) => \[\] as Feedback\[\]\)/)
  assert.match(practice, /const everyAnswerSaved=workspace\?\.items\.length===5/)
  assert.match(practice, /workspace\.items\.every\(question=>seen\.has\(question\.id\)\)/)
  assert.match(practice, /if\(!workspace \|\| busy \|\| !everyAnswerSaved\)return/)
  assert.doesNotMatch(practice, /if\(!workspace \|\| busy \|\| feedback\.length!==5\)return/)
  assert.match(practice, /await submitAttempt\(workspace\.attemptId\)/)
  assert.match(practice, /setFinished\(result\)[\s\S]*?play\('complete'\)/)
  assert.match(practice, /Retry feedback/)
  assert.match(practice, /feedbackReady\s*\?\s*<p/)
  assert.match(practice, /Your attempt is saved\. Detailed review is temporarily unavailable/)
  assert.match(practice, /finished\.scoreReleased/)
})

test('Exam remains server-authoritative with autosave, skip, expiry, review gate', () => {
  const exam = read('app/student/assessment/[assignmentId]/page.tsx')
  const result = read('app/student/results/[attemptId]/page.tsx')
  assert.match(exam, /saveResponseWithRevision/)
  assert.match(exam, /await submitAttempt\(workspace\.attemptId\)/)
  assert.match(exam, /deadlineReached/)
  assert.match(exam, /recoveredDraft/)
  assert.match(exam, /activeElsewhere/)
  assert.match(exam, /showConfirm/)
  assert.match(exam, /skippedAtSubmission/)
  assert.doesNotMatch(exam, /play\(['"](?:correct|retry)['"]/)
  assert.match(exam, /result\.scoreReleased/)
  assert.match(result, /result\.answersRevealed/)
  assert.match(result, /Recover missed and skipped learning outcomes/)
})

