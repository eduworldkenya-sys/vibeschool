import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(path, 'utf8')
const results = read('app/student/results/[attemptId]/page.tsx')
const revision = read('app/student/vibelearn/revision/page.tsx')
const exams = read('app/student/vibelearn/exams/page.tsx')
const practice = read('app/student/vibelearn/practice/page.tsx')
const mistakes = read('app/student/vibelearn/mistakes/page.tsx')
const recovery = read('app/student/vibelearn/recovery/page.tsx')
const exactRecoverySql = read('supabase/migrations/20261112200000_exact_learning_recovery.sql')
const topicPractice = read('app/student/vibelearn/topic-practice/page.tsx')

assert.match(results, /result\.canRetry\s*&&/, 'Retake action must follow server canRetry flag')
assert.match(results, /encodeURIComponent\(result\.assignmentId\)/, 'Retake must target the same assessment assignment')
assert.match(results, /Try this exam again/, 'Retake button must communicate intended action')
assert.doesNotMatch(results, /Open My Assessments/, 'No generic assessment hub redirect from retake card')
assert.match(results, /\/student\/vibelearn\/exams/, 'Results must offer a canonical back-to-exams route')
assert.match(exams, /listMyAssessmentAssignments/, 'Exam discovery must use canonical assignments')
assert.match(practice, /recordGroundedPracticeAnswer/, 'Practice scoring remains canonical')
assert.match(mistakes, /\/student\/vibelearn\/recovery\?mistake=/, 'Mistakes navigate to exact outcome recovery')
assert.doesNotMatch(mistakes, /verifyMistakeMastery|resolveMistake/, 'Broad-topic mastery verification must not resolve exact mistakes')
assert.match(results, /Recover this exact question/, 'Released wrong and skipped responses must open the matching outcome')
assert.match(recovery, /student_get_exact_learning_recovery/, 'Recovery uses the learner-only evidence RPC')
assert.match(recovery, /recordGroundedPracticeAnswer/, 'Recovery reassessment must use existing server scoring')
assert.doesNotMatch(recovery, /markMastered|markRevised|updateMastery|setMastery/, 'Opening recovery must never award mastery')
assert.match(exactRecoverySql, /vs_guard_mistake_resolution/, 'All mistake status updates must enforce exact evidence')
assert.match(exactRecoverySql, /vs_exact_recovery_proof/, 'Mastery resolution must use exact-outcome server proof')
assert.match(exactRecoverySql, /correct_distinct_questions>=3 and correct_distinct_days>=2/, 'Three different correct questions across two days are required')
assert.match(exactRecoverySql, /student_record_vibelearn_practice_skip/, 'Skipped questions require durable zero-credit receipts')
assert.match(topicPractice, /student_record_vibelearn_practice_skip/, 'Topic Practice sends skips to the canonical evidence store')
assert.doesNotMatch(topicPractice, /completedTopics/, 'A finished or skipped session cannot imply mastery')
assert.doesNotMatch(revision, /Mark understood/, 'Revision must not provide competing mistake resolution')
assert.doesNotMatch(revision, /resolveMistake/, 'Revision must not invoke the old resolution shortcut')
assert.match(revision, /daysRemaining > 0/, 'Expired or unset exam date should not show a misleading countdown')
console.log('Learner retake, exact-outcome recovery, revision and mastery navigation: PASS')
