import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'
const read = path => readFileSync(path,'utf8')
test('Learn and Practice have distinct visible owners without a second question or content engine', () => {
 const student=read('app/student/study/page.tsx')
 const links=read('components/student/StudentLearningFeatureLinks.tsx')
 const library=read('components/learn/SchoolLearnLibrary.tsx')
 const topic=read('app/student/vibelearn/topic-practice/page.tsx')
 const canonical=read('components/student/CanonicalTopicPractice.tsx')
 assert.match(student, /StudentLearningFeatureLinks mode="learn"/)
 assert.doesNotMatch(student, /aria-label="Available practice"/)
 assert.match(library, /useState<'lessons' \| 'resources'>/)
 assert.doesNotMatch(library, /tab === 'practice'/)
 assert.doesNotMatch(library, /tab === 'revision'/)
 assert.match(library, /Finished learning\? Practise this subject/)
 assert.match(links, /readers|Published|published/)
 assert.match(links, /mode==='learn'\?learn:practice/)
 assert.match(links, /href:'\/student\/vibelearn\/mistakes'/)
 assert.match(links, /href:'\/student\/vibelearn\/revision'/)
 assert.match(links, /href:'\/student\/marks'/)
 assert.match(topic, /visibleTopics\.map/)
 assert.match(topic, /subject=\{requestedSubject\}/)
 assert.match(canonical, /<StudentLearningFeatureLinks mode="practice"/)
 assert.match(canonical, /item\.hint && !seen\.has\(item\.id\)/)
 assert.match(canonical, /saveResponse\(/)
 assert.match(canonical, /startOrResumeAttempt/)
 assert.match(canonical, /submitAttempt\(/)
 const nav=read('components/student/BottomNav.tsx')
 assert.match(nav, /path\.startsWith\("\/student\/vibelearn\/revision"\)/)
 assert.match(nav, /path\.startsWith\("\/student\/vibelearn\/mistakes"\)/)
 assert.match(nav, /path\.startsWith\("\/student\/vibelearn\/exams"\)/)
 assert.doesNotMatch(links, /supabase|saveResponse|submitAttempt|fetch\(/)
})
