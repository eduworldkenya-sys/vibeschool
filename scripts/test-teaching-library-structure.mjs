import assert from 'node:assert/strict'
import fs from 'node:fs'
import {
  TEACHING_LIBRARY_CATEGORIES,
  TEACHING_LIBRARY_SLOTS,
  filterTeachingLibrarySlots,
  teachingLibrarySlotForResource,
} from '../lib/teaching/libraryStructure.ts'

const groups = new Set(TEACHING_LIBRARY_CATEGORIES.map(item => item.id))
assert.equal(groups.size, 5, 'five distinct teaching resource groups')
assert.equal(TEACHING_LIBRARY_SLOTS.length, 15, 'all 15 planned resource slots exist')
assert.equal(new Set(TEACHING_LIBRARY_SLOTS.map(item => item.id)).size, 15, 'slot IDs are stable and unique')
assert.ok(TEACHING_LIBRARY_SLOTS.every(item => groups.has(item.categoryId)))
assert.equal(filterTeachingLibrarySlots('').length, 15, 'empty search must show all empty slots')
assert.equal(filterTeachingLibrarySlots('   ').length, 15, 'blank search must show all empty slots')
assert.equal(filterTeachingLibrarySlots('No match').length, 0, 'unmatched search is a valid empty state')
assert.deepEqual(filterTeachingLibrarySlots('revision').map(item => item.id), ['revision'])
assert.deepEqual(filterTeachingLibrarySlots(' QUIZZES ').map(item => item.id), ['quizzes'])
assert.deepEqual(filterTeachingLibrarySlots('', 'check-learning').map(item => item.id), ['quizzes', 'tests-exams'])
assert.deepEqual(filterTeachingLibrarySlots('experiments', 'check-learning'), [])
assert.deepEqual(filterTeachingLibrarySlots('support', 'support-improve').length, 3)
const linkedTypes = TEACHING_LIBRARY_SLOTS.filter(item => item.existingPersonalResourceType)
assert.deepEqual(linkedTypes.map(item => item.existingPersonalResourceType), ['notes', 'quiz'])
// No test/example records or resources are generated by the structural taxonomy.
assert.ok(TEACHING_LIBRARY_SLOTS.every(item => !('content' in item)))
console.log('Teaching Library structure contracts passed: 5 categories, 15 slots, search, empty states, no synthetic content.')


const variantExamples = [
  ['lesson_notes', 'lesson-notes'],
  ['worked_example', 'worked-examples'],
  ['diagram', 'illustrations-diagrams'],
  ['demonstration', 'demonstrations'],
  ['experiment', 'experiments'],
  ['discussion', 'discussions'],
  ['project', 'projects'],
  ['assignment', 'assignments'],
  ['homework', 'homework'],
  ['quiz', 'quizzes'],
  ['exam', 'tests-exams'],
  ['revision', 'revision'],
  ['educational_game', 'educational-games'],
  ['reflection', 'reflection'],
  ['enrichment', 'remedial-enrichment'],
]
assert.equal(variantExamples.length, 15)
for (const [variant, expected] of variantExamples) {
  assert.equal(teachingLibrarySlotForResource({ materialVariant: variant }), expected, variant)
}
assert.equal(teachingLibrarySlotForResource({ materialVariant: '  worked-example  ' }), 'worked-examples', 'normalizes hyphens')
assert.equal(teachingLibrarySlotForResource({ materialVariant: null, assetKind: 'learner_notes' }), 'lesson-notes')
assert.equal(teachingLibrarySlotForResource({ assetKind: 'worked_example' }), 'worked-examples')
assert.equal(teachingLibrarySlotForResource({ resourceRole: 'homework_source' }), 'homework')
assert.equal(teachingLibrarySlotForResource({ purpose: 'remediate' }), 'remedial-enrichment')
assert.equal(teachingLibrarySlotForResource({ assetKind: 'content_block' }), null, 'generic content cannot be guessed')
assert.equal(teachingLibrarySlotForResource({ assetKind: 'practical' }), null, 'practical is not automatically an experiment')
assert.equal(teachingLibrarySlotForResource({ assetKind: 'assessment' }), null, 'generic assessment is not automatically an exam')
assert.equal(teachingLibrarySlotForResource({ assetKind: 'worksheet' }), null, 'worksheet is not automatically an assignment')
assert.equal(teachingLibrarySlotForResource({ title: 'Exam Tips' }), null, 'resource title cannot classify')
assert.equal(teachingLibrarySlotForResource({}), null, 'empty metadata is valid')
assert.ok(TEACHING_LIBRARY_SLOTS.every(item => !('required' in item) && !('minimum' in item)), 'no slot may be compulsory')

