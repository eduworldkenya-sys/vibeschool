import {test} from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
const read=file=>fs.readFileSync(new URL('../'+file,import.meta.url),'utf8')
test('Web Push never exposes a private device or dispatch job to users',()=>{
 const sql=read('supabase/migrations/20261124235500_vibechat_web_push.sql')
 assert.match(sql,/revoke all on private\.vibechat_push_devices from public,anon,authenticated/)
 assert.match(sql,/revoke all on private\.vibechat_push_jobs from public,anon,authenticated/)
 assert.match(sql,/s\.id=d\.session_id and s\.user_id=d\.profile_id/)
 assert.match(sql,/not private\.vibechat_pair_blocked\(d\.profile_id,p_sender\)/)
 assert.match(sql,/p\.room_id=p_room and p\.muted/)
 assert.match(sql,/r\.read_at>=case/)
 assert.match(sql,/for update skip locked/)
 assert.match(sql,/j\.lease_token=p_lease and j\.lease_until>now\(\)/)
 assert.match(sql,/grant execute on function public\.vibechat_claim_push\(\) to service_role/)
 assert.match(sql,/d\.profile_id<>actor/)
 assert.match(sql,/private\.vibechat_valid_push_endpoint/)
})
test('Worker is authenticated, allowlisted and sends generic empty pushes',()=>{
 const worker=read('supabase/functions/vibechat-push-dispatch/index.ts')
 const sw=read('public/sw.js')
 const client=read('components/vibechat/useVibeChatWebPush.ts')
 assert.match(worker,/sameSecret\(req\.headers\.get\("x-vibechat-dispatch-secret"\)/)
 assert.match(worker,/validEndpoint\(d\.endpoint\)/)
 assert.match(worker,/redirect:"error"/)
 assert.match(worker,/Authorization:await authorization\(d\.endpoint,key\),TTL:"60"/)
 assert.match(worker,/vibechat_push_delivery/)
 assert.match(sw,/self\.addEventListener\('push'/)
 assert.match(sw,/body:'You have a new message\.'/)
 assert.match(client,/Notification\.requestPermission/)
 assert.match(client,/userVisibleOnly:true/)
 assert.match(client,/localStorage\.getItem\(PUSH_OWNER_KEY\)!==current/)
 assert.match(client,/subscription\.unsubscribe/)
})
