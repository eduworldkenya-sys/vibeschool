import assert from 'node:assert/strict'
import { readFileSync, existsSync } from 'node:fs'
import test from 'node:test'

const read=path=>readFileSync(path,'utf8')

test('Learn owns a single canonical discovery shell for all published content',()=>{
  const root=read('app/learn/page.tsx')
  const library=read('components/learn/SchoolLearnLibrary.tsx')
  const navigation=read('components/learn/LearnNavigation.tsx')
  const extensions=read('components/learn/UnifiedLearnCollections.tsx')
  const styles=read('components/learn/SchoolLearnLibrary.module.css')
  assert.match(root, /SchoolLearnLibrary mode="public"/)
  assert.match(library, /const basePath = '\/learn'/)
  assert.match(library, /<UnifiedLearnCollections view=\{collectionView\}/)
  assert.match(navigation, /href="\/learn\?view=reading"/)
  assert.match(navigation, /href="\/learn\?view=courses"/)
  assert.match(library, /href="\/student\/study"/)
  assert.match(library, /href=\{reader\.href\}/, 'Keep certified topic reader URLs')
  assert.match(library, /\/read\/textbook\//, 'Keep existing canonical textbook reader')
  assert.match(extensions, /\.eq\('status','published'\)/, 'No drafts in general publications')
  assert.match(extensions, /publication\.format === 'vibetextbook'/, 'Textbooks use authorized textbook reader')
  assert.match(extensions, /\/global\/read\/publication\//, 'Other publications keep authorized reader')
  assert.match(extensions, /course\.status==='live'/, 'Courses in review must not launch')
  assert.match(extensions, /\/learn\/'\+encodeURIComponent\(course\.slug\)/, 'Existing live course slugs preserved')
  assert.match(styles, /\.collectionsFrame/, 'Common shell must keep full reading width')
  assert.doesNotMatch(extensions, /service_role|certified_at\s*=|\.eq\('status','draft'\)/)
})

test('all legacy catalogue landing pages hand off; deep readers and practice remain',()=>{
  const courses=read('app/learn/courses/page.tsx')
  const global=read('app/global/read/page.tsx')
  const student=read('app/student/vibelearn/page.tsx')
  const reading=read('app/student/vibelearn/reading/page.tsx')
  const layout=read('app/student/vibelearn/layout.tsx')
  const redirect=read('components/learn/StudentLearnLegacyRedirect.tsx')
  assert.match(courses,/redirect\('\/learn\?view=courses'\)/)
  assert.match(global,/redirect\('\/learn\?view=reading'\)/)
  assert.match(student,/redirect\('\/student\/study'\)/, 'Legacy VibeLearn landing returns to the protected learner desk')
  assert.match(reading,/StudentLearnLegacyRedirect/)
  assert.match(layout,/return <>\{children\}<\/>/, 'No legacy grade-based landing may intercept nested routes')
  assert.match(redirect,/recogniseLearnerGrade\(identity\?\.className\)/)
  assert.match(redirect,/prior\.get\('subject'\)/, 'Preserve deep subject links')
  assert.match(redirect,/router\.replace\('\/learn'/)
  assert.ok(existsSync('app/learn/grade-4/mathematics/time/page.tsx'))
  assert.ok(existsSync('app/learn/grade-1/creative-activities/page.tsx'))
  assert.ok(existsSync('app/learn/[courseSlug]/page.tsx'))
  assert.ok(existsSync('app/learn/[courseSlug]/[moduleSlug]/[topicSlug]/page.tsx'))
  assert.ok(existsSync('app/read/textbook/[publicationId]/page.tsx'))
  assert.ok(existsSync('app/global/read/publication/[id]/page.tsx'))
  assert.ok(existsSync('app/student/vibelearn/exams/page.tsx'))
  assert.ok(existsSync('app/student/vibelearn/practice/page.tsx'))
  assert.ok(existsSync('app/student/vibelearn/topic-practice/page.tsx'))
  assert.ok(existsSync('app/student/vibelearn/revision/page.tsx'))
})

test('personal learner data stays behind student identity, not the public catalogue',()=>{
  const desk=read('app/student/study/page.tsx')
  const nav=read('components/student/BottomNav.tsx')
  const home=read('app/student/page.tsx')
  assert.match(desk,/useStudent\(\)/, 'Use canonical student identity gate')
  assert.match(desk,/getVibeLearnWorkstation/)
  assert.match(desk,/getAssignedReading/)
  assert.match(desk,/getAdaptiveLearningPath/)
  assert.match(desk,/getAdaptiveResourceRecommendations/)
  assert.match(desk,/getExamReadinessBrief/)
  assert.match(desk,/updateExamReadiness/)
  assert.match(desk,/href="\/student\/tasks"/)
  assert.match(desk,/href="\/student\/vibelearn\/exams"/)
  assert.match(desk,/safeInternalRoute\(item\.actionUrl/, 'Do not directly trust action URLs')
  assert.match(nav,/href: "\/student\/study"/, 'Student Learn tab must target the personal learning desk')
  assert.match(home,/router\.push\('\/student\/study'\)/, 'Student home Learn must open the personal learning desk')
  const publicRoot=read('app/learn/page.tsx')
  assert.doesNotMatch(publicRoot,/getExamReadinessBrief|getAssignedReading|StudentProvider/, 'No private student data in public shell')
})
