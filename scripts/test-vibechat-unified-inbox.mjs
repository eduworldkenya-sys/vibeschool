test('outbox retains one operation key across retries and rechecks room authority',()=>{
  const outbox=read('components/vibechat/useVibeChatOutbox.ts')
  const ui=read('components/vibechat/VibeChat.tsx')
  const sql=read('supabase/migrations/20261124235200_vibechat_idempotent_send.sql')
  assert.match(sql,/primary key\(sender_id,operation_id\)/)
  assert.match(sql,/p_owner is distinct from v_user/)
  assert.match(sql,/private\.vibechat_room_peer\(p_kind,p_room\)/)
  assert.match(sql,/private\.vibechat_pair_blocked\(v_user,v_peer\)/)
  assert.match(sql,/pg_advisory_xact_lock/)
  assert.match(sql,/v_existing\.body_digest<>v_digest/)
  assert.match(sql,/return v_existing\.message_id/)
  assert.match(sql,/revoke all on private\.vibechat_send_operations from public,anon,authenticated/)
  assert.match(outbox,/p_operation:item\.id/)
  assert.match(outbox,/id:crypto\.randomUUID\(\)/)
  assert.match(outbox,/firstByRoom/)
  assert.match(outbox,/currentOwner\.current!==actor/)
  assert.match(outbox,/event==='SIGNED_OUT'/)
  assert.match(outbox,/sessionStorage\.removeItem\(storageKey\)/)
  assert.match(outbox,/navigator\.onLine/)
  assert.match(ui,/outbox\.enqueue/)
  assert.match(ui,/Queued offline/)
  assert.match(ui,/outbox\.retry\(item\.id\)/)
})
