import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8')
const index = JSON.parse(read('content/curriculum/grade9-english-2024-index.json'))
const map = read('components/teacher/curriculum/Grade9EnglishMap.tsx')
const teacher = read('app/teacher/scheme/AuthoritySchemePage.jsx')
const migration = read('supabase/migrations/20261111101500_grade9_english_revised_index.sql')

assert.equal(index.grade, 'Grade 9')
assert.equal(index.learningArea, 'English')
assert.equal(index.weeklyLessons, 5)
assert.equal(index.suggestedLessons, 150)
assert.equal(index.themes.length, 15)
assert.equal(index.verification, 'structure_crosschecked_outcomes_pending')
assert.ok(index.officialIndexUrl.startsWith('https://kicd.ac.ke/'))
const all = index.themes.flatMap(theme => {
  assert.equal(theme.units.length, 5, 'All 15 KICD themes require five skill units')
  assert.deepEqual(theme.units.map(unit => unit.code), [1,2,3,4,5].map(lane => `${theme.number}.${lane}.1`))
  return theme.units
})
assert.equal(all.length, 75)
assert.equal(new Set(all.map(unit => unit.code)).size, 75)
assert.equal(all.reduce((sum, unit) => sum + unit.suggestedLessons, 0), 150)
assert.ok(all.every(unit => unit.title.trim() && unit.strand.trim() && unit.suggestedLessons === 2))
assert.ok(all.every(unit => !('outcomes' in unit) && !('experiences' in unit)))
assert.ok(map.includes('grade9-english-theme') && map.includes('grade9-english-search'))
assert.ok(map.includes('View original KICD source'))
assert.ok(map.includes('onOpenScheme') && map.includes('learning outcomes'))
assert.ok(teacher.includes("import Grade9EnglishMap from '@/components/teacher/curriculum/Grade9EnglishMap'"))
assert.ok(teacher.includes('isGrade9English') && teacher.includes('curriculumView && isGrade9English && <Grade9EnglishMap'))
assert.ok(teacher.includes('isGrade9English?\'none\'') || teacher.includes('||isGrade9English?\'none\''))
assert.ok(migration.includes('on conflict (subject_id,grade,name,sub_strand) do nothing'))
assert.ok(migration.includes('GRADE9_ENGLISH_SOURCE_INDEX_INCOMPLETE'))
assert.ok(migration.includes('GRADE9_ENGLISH_INDEX_REGISTRATION_INCOMPLETE'))
assert.ok(migration.includes("source_ref like 'VS-REF-G09-EN-2024#%'"))
assert.ok(!migration.includes('delete from public.cbc_strands'))
assert.ok(!migration.includes('insert into public.scheme_of_work'))
assert.ok(!migration.includes('insert into public.curriculum_learning_outcomes'))
console.log('Grade 9 English revised structure, 75-unit index, source links, and native curriculum route: PASS')
