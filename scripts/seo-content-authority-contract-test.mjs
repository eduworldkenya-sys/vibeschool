import assert from 'node:assert/strict'
import fs from 'node:fs'
const read=path=>fs.readFileSync(path,'utf8')
const layout=read('app/layout.tsx')
const article=read('app/blog/[id]/page.tsx')
const guide=read('app/kenya-education/[slug]/page.tsx')
const sitemap=read('app/sitemap.ts')
const robots=read('app/robots.ts')
const blogContent=read('lib/blogContent.ts')
assert.match(layout,/EducationalOrganization/,'site must expose education organization schema')
assert.match(layout,/knowsAbout/,'organization must declare its real education subject areas')
assert.match(layout,/KCSE revision/,'site metadata must cover core Kenyan education discovery intent')
assert.match(article,/keywords/,'article metadata must derive discovery terms from editorial tags')
assert.match(article,/BreadcrumbList/,'articles must expose breadcrumb structured data')
assert.match(article,/publisher:\{'@type':'EducationalOrganization','@id':`\$\{SITE_URL\}\/\#organization`/,'articles must link publisher to canonical organization identity')
assert.match(article,/dateModified/,'articles must expose modification freshness')
assert.match(guide,/citation:sources\.map/,'source-backed guides must expose citations in structured data')
assert.match(guide,/BreadcrumbList/,'guides must expose breadcrumb structured data')
assert.match(guide,/robots:\{index:true,follow:true\}/,'valid guides must be explicitly indexable')
assert.match(blogContent,/filter\(isPublicBlogReady\)/,'thin or incomplete VibePress content must stay out of the public newsroom')
assert.match(sitemap,/listKnowledgeArticles/,'authority guides must be discoverable through the sitemap')
assert.match(robots,/\/blog\//,'blog must remain crawlable')
assert.match(robots,/\/kenya-education\//,'authority guides must remain crawlable')
console.log('SEO content authority contract: PASS')
