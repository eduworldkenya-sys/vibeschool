const match=sql.match(/from jsonb_array_elements\(\$catalog\$([\s\S]*?)\$catalog\$::jsonb\) unit;/)
assert.ok(match,'The migration must store the exact source-linked application catalog')
assert.deepEqual(JSON.parse(match[1]),units,'Never drift between UI and database lesson/outcome identities')
const terms=[1,2,3].map(n=>({id:'t'+n,term:n}))
const termWeeks=terms.flatMap(t=>Array.from({length:10},(_,i)=>({term_id:t.id,week_number:i+1,week_type:'normal',school_id:null})))
const options={units,terms,termWeeks,weeklyAllocation:5,expectedUnitCount:19,gradeLabel:'Grade 4'}
const draft=buildGrade1AnnualSchemeDraft(options)
assert.equal(draft.error,null)
assert.equal(draft.items.length,150)
assert.equal(draft.unitCount,19)
assert.equal(draft.weeks.length,30)
assert.equal(new Set(draft.items.map(x=>x.key)).size,150)
assert.deepEqual(new Set(draft.items.map(x=>x.unitId)),new Set(units.map(x=>x.id)))
assert.ok(draft.weeks.every(w=>draft.items.filter(x=>x.termId===w.termId&&x.week===w.week).length===5))
assert.deepEqual(buildGrade1AnnualSchemeDraft(options),draft,'Repeat visits must be deterministic')
assert.equal(terms.reduce((n,t)=>n+termCreativeSchemeRows(draft,t.id).length,0),150)
assert.ok(buildGrade1AnnualSchemeDraft({...options,weeklyAllocation:4}).error,'Insufficient teacher allocation fails closed')
assert.ok(buildGrade1AnnualSchemeDraft({...options,terms:terms.slice(0,2)}).error,'Missing term calendar fails closed')
