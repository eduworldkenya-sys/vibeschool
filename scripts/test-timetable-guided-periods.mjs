import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source=fs.readFileSync('lib/timetable/periods.ts','utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ES2022}}).outputText;
const {periodsForDay,teachingBlock,protectedBlockConflict}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const period=(id,start,end,kind='lesson',school='school',day=0)=>({id,school_id:school,schedule_day:day,period_number:1,label:kind,start_time:start,end_time:end,kind,protected:kind!=='lesson'});
const all=[period('a','08:00:00','08:35:00'),period('b','08:35:00','09:10:00'),period('break','09:10:00','09:30:00','break'),period('c','09:30:00','10:05:00'),period('other','08:00','09:00','lesson','other'),period('tuesday','10:05','10:40','lesson','school',2)];
const monday=periodsForDay(all,'school',1);
assert.equal(monday.length,4);
assert.equal(teachingBlock(monday,'a',2).at(-1).end_time,'09:10:00');
assert.equal(teachingBlock(monday,'b',2),null,'double must not cross break');
assert.equal(teachingBlock(monday,'c',2),null,'cannot extend beyond school periods');
assert.equal(teachingBlock(monday,'missing',1),null);
assert.equal(teachingBlock(monday,'a',1.5),null);
assert.equal(teachingBlock(monday,'a',0),null);
assert.equal(protectedBlockConflict(monday,'08:35','09:30').id,'break');
assert.equal(protectedBlockConflict(monday,'08:35','09:10'),undefined,'adjacency is valid');
assert.equal(protectedBlockConflict(monday,'09:30','10:05'),undefined);
console.log('Guided timetable period regressions: PASS');

const React=await import('react');
const {renderToStaticMarkup}=await import('react-dom/server');
const {default:Grid}=await import('../components/teacher/ClassicTimetable.tsx');
const blocks=monday.map(p=>({id:p.id,scheduleDay:p.schedule_day,periodNumber:p.period_number,label:p.label,startTime:p.start_time,endTime:p.end_time,kind:p.kind,protected:p.protected}));
const slot=(overrides={})=>({id:'slot',subject:'Maths',className:'Grade 8 Blue',room:'4',startTime:'08:00',endTime:'09:10',dayOfWeek:1,effectiveFrom:'2026-01-01',effectiveUntil:null,...overrides});
const render=(slots,dayBlocks=blocks)=>renderToStaticMarkup(React.createElement(Grid,{slots,blocks:dayBlocks,dateForDow:()=> '2026-10-05',onSelect:()=>{},onAdd:()=>{}}));
let markup=render([slot()]);
assert.ok(markup.includes('rowspan="2"'),'double lesson spans two periods');
assert.equal((markup.match(/>Maths</g)||[]).length,1,'double is displayed once');
assert.ok(!markup.includes('>Sat<'),'generic school periods do not invent weekend teaching');
assert.ok(!render([slot({effectiveUntil:'2026-01-02'})],[]).includes('Maths'),'expired slots do not create rows');
markup=render([slot({endTime:'08:20'})]);
assert.ok(!markup.includes('aria-label="Add lesson Mon 08:20"'),'partial occupied period is not offered as a free full period');
markup=render([slot(),slot({id:'overlap',subject:'English',startTime:'08:35',endTime:'09:10'})]);
assert.ok(!markup.includes('rowspan="2"'),'overlap remains visible without corrupting columns');
assert.ok(markup.includes('English'));
console.log('Weekly grid rendering regressions: PASS');
