import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(path,'utf8')
const topic = read('app/student/vibelearn/topic-practice/page.tsx')
const canonical = read('components/student/CanonicalTopicPractice.tsx')
const recovery = read('app/student/vibelearn/recovery/page.tsx')
const mistakes = read('app/student/vibelearn/mistakes/page.tsx')
const revision = read('app/student/vibelearn/revision/page.tsx')
const practice = read('app/student/vibelearn/practice/page.tsx')
const lib = read('lib/student/vibelearn.ts')
const sql = read('supabase/migrations/20261112105000_student_mistake_source_context.sql')

assert.match(topic,/CanonicalTopicPractice grade=\{grade\}/,'grade routes reuse canonical EXQ')
assert.match(topic,/\[1-9\]\|1\[0-2\]/,'Grade 4 must route through canonical practice')
assert.match(canonical,/listMyAssessmentAssignments\(\)/,'fallback uses learner-scoped canonical discovery')
assert.match(canonical,/question counts/,'12-item assessments cannot be called five-question drills')
assert.match(canonical,/otherPractice\.map/,'learner must have an alternative to empty topics')
assert.match(recovery,/: error \? null/,'DB errors must not be rendered as empty recovery')
assert.match(recovery,/Retry recovery/,'backend errors remain actionable')
assert.match(lib,/student_get_my_mistake_source_grades/,'provenance is scoped to signed-in learner')
assert.match(lib,/sourceVerified: provenance\.get/,'unverified sources are not current-grade recommendations')
assert.match(mistakes,/historicMistakes\.map/,'history stays reviewable, never deleted')
assert.match(mistakes,/currentMistakes\.map/,'current-grade recovery excludes historical questions')
assert.match(revision,/historicalOnlyKeys/,'historical-only topics cannot be promoted')
assert.doesNotMatch(practice,/\|\| 'Other'/,'misleading Other filter is removed')
assert.match(sql,/m\.student_id=v_student/,'source-grade lookup is learner-owned')
assert.match(sql,/grant execute on function public\.student_get_my_mistake_source_grades/,'authenticated only')
assert.doesNotMatch(sql,/grant execute[\s\S]*to anon/i,'no anonymous access')
console.log('PASS: learner recovery, Grade 4 practice fallback and historic grade isolation')
