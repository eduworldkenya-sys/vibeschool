import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(path, 'utf8')
const source = read('lib/curriculum/grade8KiswahiliReference.ts')
const reader = read('components/teacher/curriculum/Grade8KiswahiliMap.tsx')
const scheme = read('app/teacher/scheme/AuthoritySchemePage.jsx')
const match = source.match(/export const GRADE8_KISWAHILI_THEMES = (\[[\s\S]*?\]) as const/)
assert.ok(match, 'Curriculum must define all 15 canonical theme labels')
const themes = JSON.parse(match[1])
assert.equal(themes.length, 15)
assert.deepEqual(themes.map(x => x.number), Array.from({length:15}, (_,i)=>i+1))
assert.deepEqual(themes.map(x => x.topics.length), Array(15).fill(4))
const codes=themes.flatMap(t=>t.topics.map((_, i)=>String(t.number)+'.'+String(i+1)+'.1'))
assert.equal(codes.length,60)
assert.equal(new Set(codes).size,60)
assert.equal(themes.length*4*2,120)
assert.ok(source.includes('GRADE8_KISWAHILI_WEEKLY_LESSONS = 4'))
assert.ok(source.includes('https://kicd.ac.ke/wp-content/uploads/2024/09/GRADE-8-KISWAHILI.pdf'))
assert.ok(scheme.includes(String.raw`/^grade\s*8$/i`))
assert.ok(scheme.includes('isGrade8Kiswahili && <Grade8KiswahiliMap'))
assert.ok(scheme.includes('(isGrade8Kiswahili&&!showEnglishLegacy)'))
assert.ok(reader.includes('kiswahili-grade8-search'))
assert.ok(reader.includes('onOpenScheme'))
assert.ok(reader.includes('onToggleExisting'))
assert.ok(reader.includes('GRADE8_KISWAHILI_UNITS'))
assert.ok(!reader.includes('iframe'))
assert.ok(!source.includes('learning_outcomes'), 'Official full outcome text must not be silently certified')
console.log('Grade 8 Kiswahili source-reference curriculum contract: PASS')
