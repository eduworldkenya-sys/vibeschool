assert.match(recovery, /play\(correct \? 'correct' : 'retry'\)/)
assert.match(language, /play\(correct \? 'correct' : 'retry'\)/)
assert.match(time, /option === check\.correct \? 'correct' : 'retry'/)
assert.match(practical, /Drawing downloaded to this device\. It has not been submitted/)
// No saving/submission sounds before the server-authoritative receipt.
assert.match(homework, /await submitStudentHomework[\s\S]*?play\("submitted"\)/)
assert.match(exercises, /if \(receiptError\) throw[\s\S]*?play\("submitted"\)/)
assert.match(projects, /if \(err\)[\s\S]*?play\('submitted'\)/)
assert.match(independent, /if \(writeError\) throw writeError;[\s\S]*?play\(complete \? "submitted" : "saved"\)/)
assert.match(tasks, /if\(saveError\|\|!data\)[\s\S]*?play\(completed_at\?'complete':'select'\)/)
console.log('Unified feedback contract PASS: one audio engine, student theme, marking and confirmed receipts.')
