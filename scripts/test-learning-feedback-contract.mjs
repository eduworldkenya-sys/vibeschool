assert.match(read('app/layout.tsx'), /<LearningFeedbackProvider>\{children\}<\/LearningFeedbackProvider>/)
assert.match(studentLayout, /<FeedbackSoundToggle \/>/)
assert.match(read('components/learn/tools/TeachingToolShelf.tsx'), /<FeedbackSoundToggle\s*\/>/)
