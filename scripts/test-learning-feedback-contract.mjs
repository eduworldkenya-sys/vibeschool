const feedback = read('components/student/LearningFeedback.tsx')
const css = read('components/student/learning-feedback.css')
const facade = read('components/learn/LearningFeedback.tsx')
const studentLayout = read('app/student/layout.tsx')
const exam = read('app/student/assessment/[assignmentId]/page.tsx')
const canonical = read('components/student/CanonicalTopicPractice.tsx')
const topic = read('app/student/vibelearn/topic-practice/page.tsx')
const recovery = read('app/student/vibelearn/recovery/page.tsx')
