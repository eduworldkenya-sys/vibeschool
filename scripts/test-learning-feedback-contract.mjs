assert.doesNotMatch(facade, /AudioContext|localStorage|createOscillator/)
assert.match(feedback, /export function LearningFeedbackProvider/)
assert.match(feedback, /export function useLearningFeedback/)
assert.match(feedback, /export function playLearningSound/)
assert.match(feedback, /localStorage\.getItem\(SOUND_KEY\) === 'on'/)
assert.match(feedback, /aria-pressed=\{soundOn\}/)
assert.match(feedback, /speechSynthesis\.speaking/)
assert.match(feedback, /AudioContext/)
assert.match(feedback, /document\.addEventListener\('pointerdown'/)
assert.match(feedback, /role="status" aria-live="polite"/)
