assert.match(css, /var\(--vs-accent/)
assert.match(read('components/learn/tools/TeachingTools.module.css'), /var\(--vs-on-accent/)

// A timed exam must never disclose correctness until release.
assert.doesNotMatch(exam, /play\(['"](?:correct|retry)['"]/)
