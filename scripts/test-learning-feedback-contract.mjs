// Existing Topic Practice sound/marking stays canonical: no duplicate event hook.
assert.match(canonical, /playLearningSound\(mark\.skipped\?'skipped'/)
assert.match(topic, /playLearningSound\(row\.correct\?'correct':'incorrect'\)/)
