#!/usr/bin/env node
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const source = path => readFileSync(path, 'utf8')
const route = source('app/api/learner/independent/home/route.ts')
const student = source('lib/student-context.tsx')
const switcher = source('app/student/qa/page.tsx')
const topic = source('app/student/vibelearn/topic-practice/page.tsx')
const shell = source('app/student/layout.tsx')
assert.match(route,/admin\.auth\.getUser\(bearer\.slice\(7\)\.trim\(\)\)/)
assert.match(route,/\.eq\('profile_id', user\.id\)\.eq\('entitlement_key', 'qa_universal_learner'\)/)
assert.match(route,/qaGrant\.source === 'owner_qa'/)
assert.match(route,/profile\.account_status === 'active'/)
assert.match(route,/user\.email_confirmed_at/)
assert.match(route,/qaError \|\| !profile/)
assert.match(student,/home\.universalTest === true/)
assert.match(switcher,/if \(!identity\?\.universalTest\)/)
assert.match(switcher,/\/learn\?grade=/)
assert.match(switcher,/topic-practice\?grade=/)
assert.match(topic,/identity\.universalTest \? searchParams\.get\('grade'\)/)
assert.match(topic,/storageKey = identity\?\.studentId/)
assert.match(shell,/universalTest=\{identity\?\.universalTest === true\}/)
assert.doesNotMatch(switcher,/from\(['"](?:students|student_classes|teacher_profiles)['"]\).*\.(?:insert|update|delete)/)
assert.doesNotMatch(switcher,/supabase\.auth\.admin/)
assert.doesNotMatch(route,/is_platform_owner\(\)/)
console.log('Universal QA learner permission, grade isolation and non-escalation static checks passed')
