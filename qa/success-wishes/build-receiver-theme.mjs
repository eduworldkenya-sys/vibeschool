// Scoped, checked-in utilities: the main application intentionally has no Tailwind processor.
// Regenerate after changing receiver classes: node qa/success-wishes/build-receiver-theme.mjs
import fs from 'node:fs'
import path from 'node:path'
import { compile } from 'tailwindcss'
import postcss from 'postcss'
const root = 'app/success-wishes'
const files = fs.readdirSync(root, { recursive: true }).filter(f => f.endsWith('.tsx')).map(f => path.join(root, f))
files.push('components/success-wishes/ReceiverShell.tsx', 'components/success-wishes/ReceiverEnvelope.tsx')
const source = files.map(f => fs.readFileSync(f, 'utf8')).join('\n')
const candidates = [...new Set(source.match(/[A-Za-z0-9_!#%.,/\[\]():@&=+?-]+/g) || [])]
const theme = fs.readFileSync('node_modules/tailwindcss/theme.css', 'utf8')
const compiler = await compile(theme + '\n.receiver-theme { @tailwind utilities; }')
// Next 14's production minifier collapses unprocessed native nesting into the
// parent rule. Emit flat selectors before that pipeline: otherwise utilities
// such as pointer-events-none and animate-spin apply to the entire receiver.
const tree = postcss.parse(compiler.build(candidates).replace(':root, :host', '.receiver-theme'))
// Flatten the generated AST, including nesting inside :where() and @media.
// Keep declarations grouped in their original order to preserve the cascade.
function flatten(container, parents = []) {
  const result = []
  let declarations = []
  function flush() {
    if (!declarations.length) return
    if (parents.length) result.push(postcss.rule({ selector: parents.join(', '), nodes: declarations }))
    else result.push(...declarations)
    declarations = []
  }
  for (const node of container.nodes || []) {
    if (node.type === 'decl' || node.type === 'comment') {
      declarations.push(node.clone())
      continue
    }
    flush()
    if (node.type === 'rule') {
      const selectors = parents.length
        ? parents.flatMap(parent => node.selectors.map(child => child.includes('&')
          ? child.replaceAll('&', parent) : parent + ' ' + child))
        : node.selectors
      result.push(...flatten(node, selectors))
    } else if (node.type === 'atrule' && node.nodes && !/keyframes$|^property$/.test(node.name)) {
      result.push(node.clone({ nodes: flatten(node, parents) }))
    } else result.push(node.clone())
  }
  flush()
  return result
}
const css = postcss.root({ nodes: flatten(tree) }).toString()
postcss.parse(css).walkRules(rule => {
  let parent = rule.parent
  while (parent && parent.type !== 'rule') parent = parent.parent
  if (parent || rule.selector.includes('&')) {
    throw Error('Receiver utilities must contain only flattened selectors')
  }
})
const output = '/* Generated by qa/success-wishes/build-receiver-theme.mjs; do not hand-edit. */\n' + css
if (process.argv.includes('--check')) {
  if (fs.readFileSync(root + '/receiver-utilities.css', 'utf8') !== output) throw Error('Receiver utilities are stale; regenerate before merging')
} else fs.writeFileSync(root + '/receiver-utilities.css', output)
