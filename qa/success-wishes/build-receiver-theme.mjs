// Scoped, checked-in utilities: the main application intentionally has no Tailwind processor.
// Regenerate after changing receiver classes: node qa/success-wishes/build-receiver-theme.mjs
import fs from 'node:fs'
import path from 'node:path'
import { compile } from 'tailwindcss'
const root = 'app/success-wishes'
const files = fs.readdirSync(root, { recursive: true }).filter(f => f.endsWith('.tsx')).map(f => path.join(root, f))
files.push('components/success-wishes/ReceiverShell.tsx', 'components/success-wishes/ReceiverEnvelope.tsx')
const source = files.map(f => fs.readFileSync(f, 'utf8')).join('\n')
const candidates = [...new Set(source.match(/[A-Za-z0-9_!#%.,/\[\]():@&=+?-]+/g) || [])]
const theme = fs.readFileSync('node_modules/tailwindcss/theme.css', 'utf8')
const compiler = await compile(theme + '\n.receiver-theme { @tailwind utilities; }')
const css = compiler.build(candidates).replace(':root, :host', '.receiver-theme')
const output = '/* Generated by qa/success-wishes/build-receiver-theme.mjs; do not hand-edit. */\n' + css
if (process.argv.includes('--check')) {
  if (fs.readFileSync(root + '/receiver-utilities.css', 'utf8') !== output) throw Error('Receiver utilities are stale; regenerate before merging')
} else fs.writeFileSync(root + '/receiver-utilities.css', output)
